// scripts/tariff-freshness.mjs — the internal tariff-freshness master table.
//
// Run:  node scripts/tariff-freshness.mjs        → writes docs/tariff-freshness.md
//       node scripts/tariff-freshness.mjs --check → exit 1 if any DISCOM has no recorded basis
//
// Why this is generated and not hand-kept: a hand-maintained freshness table is stale the
// day after it is written, and a stale freshness table is worse than none. Everything in the
// "Current on TDB" half is derived from the tariff data itself, so it cannot drift from what
// the site actually serves.
//
// What this file deliberately does NOT do is fill in the "Latest official" column. That
// requires reading each regulator's site, and inventing an answer there would put a wrong
// tariff year into the one document meant to be the source of truth about tariff years.
// It is left blank, with the evidence needed to check it quickly.

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { buildTariffDatabase } from './build-tariff-database.mjs';
import { STATE_META, ensureAll } from '../js/tariffs/registry.js';

const ROOT = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const CURRENT_FY = '2026-27';

// A tariff year older than the current one is NOT automatically stale. Regulators do not
// revise on a common calendar: Rajasthan's year runs from 1 October, Kerala's order is
// written to run to 31-Mar-2027, and several commissions expressly retain the previous
// schedule rather than issue new rates. Ranking by year alone would flag those as problems
// and bury the states that carry no evidence at all - which are the real risk.
const RETAINED = /retained|unchanged|continue|in force (to|till|until)|approved in advance|no hike|MYT|control period/i;

function classify(d) {
  const basis = (d.ratesAsOf || '').trim();
  const fy = d.tariffYear || '';
  if (!basis) return { tier: 1, status: 'RED', why: 'No order or basis recorded — cannot tell what these rates are from' };
  if (fy === CURRENT_FY) return { tier: 3, status: 'GREEN', why: 'On the current tariff year' };
  if (RETAINED.test(basis)) return { tier: 2, status: 'AMBER', why: 'Older year, but the note says the schedule was retained or runs on' };
  return { tier: 2, status: 'AMBER', why: 'Older year with no "retained" language — most likely genuinely behind' };
}

export async function buildFreshness() {
  await ensureAll();
  const db = buildTariffDatabase({ quiet: true }).db;
  const rows = [];
  for (const st of db.states) {
    for (const dc of st.discoms) {
      const c = classify(dc);
      rows.push({
        state: st.state,
        discom: dc.name,
        id: dc.id,
        fy: dc.tariffYear || '—',
        basis: (dc.ratesAsOf || '').trim(),
        source: dc.sourceUrl || st.sourceUrl || '',
        verified: !!(STATE_META[st.state] || {}).verified,
        ...c,
      });
    }
  }
  rows.sort((a, b) => a.tier - b.tier || a.state.localeCompare(b.state) || a.discom.localeCompare(b.discom));
  return rows;
}

function md(rows) {
  const today = new Date().toISOString().slice(0, 10);
  const n = rows.length;
  const byTier = t => rows.filter(r => r.tier === t);
  const esc = s => String(s || '').replace(/\|/g, '\\|');
  const cell = r => [
    esc(r.discom), esc(r.state), r.fy,
    '',                                   // ← Latest official: to be filled by a human
    r.source ? `[order](${r.source})` : '—',
    r.basis ? esc(r.basis.length > 92 ? r.basis.slice(0, 91) + '…' : r.basis) : '_none recorded_',
  ].join(' | ');

  const section = (t, title, blurb) => {
    const list = byTier(t);
    if (!list.length) return '';
    return `\n## ${title} — ${list.length} of ${n}\n\n${blurb}\n\n`
      + '| DISCOM | State | On TDB | Latest official | Source | Recorded basis |\n'
      + '|---|---|---|---|---|---|\n'
      + list.map(r => `| ${cell(r)} |`).join('\n') + '\n';
  };

  return `# Tariff freshness — master table

Generated by \`node scripts/tariff-freshness.mjs\` on ${today}. **Do not hand-edit**; edit the
tariff data and re-run.

**${n} DISCOMs across ${new Set(rows.map(r => r.state)).size} states.**
Current tariff year: FY ${CURRENT_FY}.

The **Latest official** column is intentionally blank. Filling it means reading each
regulator's site, and a guess there would corrupt the one document meant to be authoritative
about tariff years. Fill it as each is checked.

Web reconnaissance for the red tier — which states have a newer order, and which merely have
a *proposed* one sitting in consultation — is recorded in
[tariff-order-findings.md](./tariff-order-findings.md). That file carries sources and no rates.

> **A tariff year older than ${CURRENT_FY} does not by itself mean stale.** Regulators do not
> revise on a common calendar — Rajasthan's year runs from 1 October, Kerala's order is
> written to run to 31-Mar-2027, and several commissions expressly retain the previous
> schedule instead of issuing new rates. So these are ranked by **strength of evidence**,
> not by year. A state with no recorded basis is a bigger problem than a state on an older
> year that documents why.

## Priority

1. **Red** — no recorded basis. Cannot be defended if challenged. Fix first.
2. **Amber** — older year, basis recorded. Check whether a newer order exists.
3. **Green** — on the current year.

Verified against real consumer bills: **${rows.filter(r => r.verified).length}** of ${n}.
${section(1, '🔴 Red — no recorded basis', 'These carry rates with no order, date or source recorded. The year shown cannot be substantiated, and there is nothing on the page to justify it. Highest priority regardless of how old the year is.')}${section(2, '🟠 Amber — older year, basis recorded', 'A basis is recorded, so the figure is defensible, but the year is behind FY ' + CURRENT_FY + '. Some of these are legitimately current (the note says the schedule was retained or runs on); the rest most likely need a new order. The "why" is in the recorded basis — read it before assuming staleness.')}${section(3, '🟢 Green — current tariff year', 'On FY ' + CURRENT_FY + '. No action beyond the normal re-check when the next order lands.')}
---

## How to fill the Latest official column

For each row: open the Source link, find the most recent retail supply tariff order, and
record its financial year. If it matches **On TDB**, mark the row done. If it is newer, the
tariff data needs rebuilding for that state — and the rates must come from the order itself,
never from a secondary summary.
`;
}

const rows = await buildFreshness();
if (process.argv.includes('--check')) {
  const red = rows.filter(r => r.tier === 1);
  if (red.length) {
    console.error(`tariff-freshness: ${red.length} DISCOM(s) have no recorded basis:`);
    for (const r of red) console.error(`  ${r.discom} (${r.state})`);
    process.exit(1);
  }
  console.log(`tariff-freshness: all ${rows.length} DISCOMs carry a recorded basis`);
} else {
  const out = path.join(ROOT, 'docs', 'tariff-freshness.md');
  fs.mkdirSync(path.dirname(out), { recursive: true });
  fs.writeFileSync(out, md(rows), 'utf8');
  const t = n => rows.filter(r => r.tier === n).length;
  console.log(`tariff-freshness: ${rows.length} DISCOMs — ${t(1)} red, ${t(2)} amber, ${t(3)} green → docs/tariff-freshness.md`);
}
