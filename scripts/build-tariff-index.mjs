// scripts/build-tariff-index.mjs — generate js/tariffs/index.js, the lightweight index that
// lets registry.js answer "which states and DISCOMs exist?" without loading any tariff data.
//
// Why this exists: registry.js used to statically import all 34 per-state modules, so any page
// touching it downloaded the entire national dataset — 38 requests and ~200 KB of tariff tables
// — to render a dropdown. Measured, the metadata a dropdown actually needs is 13 KB; the other
// 187 KB is `categories`, the slab/charge tables, which are only needed once a user has chosen
// a DISCOM. This file emits the 13 KB half; registry.js pulls the rest per state on demand.
//
// Generated, not hand-written, for the same reason registry.js was: 34 state files change often
// and a hand-maintained index would silently drift. `npm run seo` rebuilds it, and
// tests/site.test.mjs fails if what is on disk is not what these sources produce.

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const ROOT = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const DIR = path.join(ROOT, 'js', 'tariffs');
const OUT = path.join(DIR, 'index.js');

// Files in js/tariffs/ that are not per-state tariff data.
const NOT_A_STATE = new Set(['registry.js', 'index.js', 'fppa.js', 'fppa-resolve.js', 'subsidy.js']);

export async function buildTariffIndex({ quiet = false } = {}) {
  const files = fs.readdirSync(DIR)
    .filter((f) => f.endsWith('.js') && !NOT_A_STATE.has(f))
    .sort();

  const states = [];
  for (const file of files) {
    const mod = (await import(pathToFileURL(path.join(DIR, file)).href)).default;
    if (!mod || !mod.state || !Array.isArray(mod.discoms)) {
      throw new Error(`build-tariff-index: ${file} does not export a { state, discoms } default`);
    }
    // Everything except the tariff tables. `categories` is the heavy half and is what the
    // lazy loader fetches later; every other field is cheap and is needed up front for
    // dropdowns, page titles, tariff-age warnings and the FPPA resolver.
    const { discoms, ...stateMeta } = mod;
    states.push({
      slug: file.replace(/\.js$/, ''),
      meta: stateMeta,
      discoms: discoms.map(({ categories, ...d }) => d),
    });
  }

  states.sort((a, b) => a.meta.state.localeCompare(b.meta.state));

  const j = (v) => JSON.stringify(v, null, 2).replace(/\n/g, '\n  ');
  const out = `// js/tariffs/index.js
// GENERATED by scripts/build-tariff-index.mjs — do not edit. Update the per-state files
// and run \`npm run seo\`.
//
// The index half of the tariff registry: which states and DISCOMs exist, plus every cheap
// field about them. The slab/charge tables (\`categories\`) are deliberately NOT here — they
// are ~93% of the data and registry.js imports them per state, on demand.

/** Map of state name -> slug of its data module, e.g. "Uttar Pradesh" -> "uttar-pradesh". */
export const STATE_SLUG = ${j(Object.fromEntries(states.map((s) => [s.meta.state, s.slug])))};

/** State-level metadata (everything the state module exports except \`discoms\`). */
export const STATE_INFO = ${j(Object.fromEntries(states.map((s) => [s.meta.state, s.meta])))};

/** Per-state DISCOM metadata, minus each DISCOM's \`categories\` tariff tables. */
export const DISCOM_INDEX = ${j(Object.fromEntries(states.map((s) => [s.meta.state, s.discoms])))};

/** Sorted state names. */
export const STATES = ${j(states.map((s) => s.meta.state))};

/** DISCOM id -> state name, so a DISCOM can be resolved without scanning every state. */
export const DISCOM_STATE = ${j(Object.fromEntries(
    states.flatMap((s) => s.discoms.map((d) => [d.id, s.meta.state]))))};
`;

  const prev = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : null;
  fs.writeFileSync(OUT, out, 'utf8');

  const discomCount = states.reduce((n, s) => n + s.discoms.length, 0);
  if (!quiet) {
    console.log(`build-tariff-index: ${states.length} states, ${discomCount} DISCOMs, ` +
      `${(out.length / 1024).toFixed(1)} KB index${prev === out ? ' (unchanged)' : ''}`);
  }
  return { bytes: out.length, states: states.length, discoms: discomCount, changed: prev !== out };
}

if (import.meta.url === pathToFileURL(process.argv[1] || '').href) await buildTariffIndex();
